"""Phase 3 (partial): walk-forward B1 Elo vs B0 de-vigged odds.

Design
- Elo K is tuned per test year using only bouts before that year (each K's predictions for a bout use
  only earlier results, so selection never sees the year being tested).
- Test window starts at TEST_START (first odds); the last 12 months of data are a locked holdout and are
  neither predicted nor scored here.
- Corner is a hash of the bout id (the source lists winners first), so A is not informative.
"""
from collections import defaultdict
from datetime import date, timedelta

import numpy as np

from ufcmodel.eval import metrics as M
from ufcmodel.eval.devig import METHODS
from ufcmodel.ratings.elo import Bout, run_elo

K_GRID = [8, 16, 32, 64, 96, 128, 192, 256]
TUNE_FROM = "2005-01-01"   # earlier bouts warm the ratings up but are not scored when tuning K
TEST_START = "2014-11-01"
MIN_SEGMENT = 100


def load_bouts(con):
    rows = con.execute("""
        SELECT b.bout_id, b.event_id, CAST(e.date AS VARCHAR), b.card_position, b.weight_class,
               r.fighter_id, r.result, u.fighter_id
        FROM bouts b JOIN events e USING (event_id)
        JOIN bout_fighter r ON r.bout_id = b.bout_id AND r.corner = 'red'
        JOIN bout_fighter u ON u.bout_id = b.bout_id AND u.corner = 'blue'
        ORDER BY e.date, b.event_id, b.card_position""").fetchall()
    score = {"win": 1.0, "loss": 0.0, "draw": 0.5, "nc": None}
    bouts = [Bout(bid, ev, d, pos or 0, a, u, score[res]) for bid, ev, d, pos, _, a, res, u in rows]
    meta = {bid: dict(weight_class=wc, date=d) for bid, _, d, _, wc, *_ in rows}
    odds = defaultdict(dict)
    for bid, fid, price in con.execute("SELECT bout_id, fighter_id, price_decimal FROM odds_snapshots").fetchall():
        odds[bid][fid] = price
    return bouts, meta, odds


def holdout_start(bouts) -> str:
    last = date.fromisoformat(max(b.date for b in bouts))
    return (last - timedelta(days=365) + timedelta(days=1)).isoformat()


def tune_and_predict(bouts, test_start, hold_start):
    preds = {k: run_elo(bouts, k) for k in K_GRID}
    chosen, out = {}, {}
    by_id = {b.bout_id: b for b in bouts}
    decisive = [b for b in bouts if b.score_a in (0.0, 1.0)]
    years = sorted({b.date[:4] for b in bouts if test_start <= b.date < hold_start})
    for y in years:
        train = [b for b in decisive if TUNE_FROM <= b.date < f"{y}-01-01"]
        ys = np.array([b.score_a for b in train])
        losses = {k: M.log_loss(np.array([preds[k][b.bout_id] for b in train]), ys) for k in K_GRID}
        chosen[y] = min(losses, key=losses.get)
        for b in bouts:
            if b.date[:4] == y and test_start <= b.date < hold_start:
                out[b.bout_id] = preds[chosen[y]][b.bout_id]
    return out, chosen, by_id


def debut_flags(bouts):
    seen, flag = defaultdict(int), {}
    i = 0
    ordered = sorted(bouts, key=lambda x: (x.date, x.event_id, x.order))
    while i < len(ordered):
        j = i
        while j < len(ordered) and ordered[j].event_id == ordered[i].event_id:
            j += 1
        for x in ordered[i:j]:
            flag[x.bout_id] = seen[x.a] == 0 or seen[x.b] == 0
        for x in ordered[i:j]:
            seen[x.a] += 1
            seen[x.b] += 1
        i = j
    return flag


def _fmt_ci(t):
    return f"{t[0]:+.4f} [{t[1]:+.4f}, {t[2]:+.4f}]"


def run(con, report_path=None):
    bouts, meta, odds = load_bouts(con)
    hold = holdout_start(bouts)
    elo, chosen_k, by_id = tune_and_predict(bouts, TEST_START, hold)
    debut = debut_flags(bouts)

    test = [by_id[i] for i in elo if by_id[i].score_a in (0.0, 1.0)]
    n_draws_nc = sum(1 for i in elo if by_id[i].score_a not in (0.0, 1.0))

    # market probabilities for bouts that have odds
    mkt = {}
    for b in test:
        o = odds.get(b.bout_id, {})
        if b.a in o and b.b in o:
            mkt[b.bout_id] = {name: f(o[b.a], o[b.b])[0] for name, f in METHODS.items()}
    common = [b for b in test if b.bout_id in mkt]
    y = np.array([b.score_a for b in common])
    p = {name: np.array([mkt[b.bout_id][name] for b in common]) for name in METHODS}
    p["elo"] = np.array([elo[b.bout_id] for b in common])
    p["coin"] = np.full(len(common), 0.5)
    ll = {k: M.per_bout_log_loss(v, y) for k, v in p.items()}

    default = min(METHODS, key=lambda m: M.ece(p[m], y))
    lines = ["# Phase 3 partial baseline: Elo vs de-vigged odds", ""]
    lines += [f"Generated by `python -m ufcmodel backtest`. Test window {TEST_START} to {hold} (exclusive); "
              f"locked holdout {hold} onward is not scored here.", ""]
    lines += ["## Scope and caveats", "",
              "- Odds come from one scraped betmma.tips pair per bout, with no opening/closing label and no timestamp. "
              "They are used as a stand-in for closing odds, so the market comparison is only approximate.",
              "- Only B0 and B1 are built. B2 (logistic) and B3 (LightGBM) need as-of features, which this dataset can't supply honestly "
              "(its fighter stats include later fights).",
              f"- Elo only (no Glicko-2 yet). K tuned per year from {K_GRID}; chosen: "
              + ", ".join(f"{yr}: {k}" for yr, k in sorted(chosen_k.items())) + ".",
              f"- {n_draws_nc} draws/no-contests in the test window are excluded from scoring.",
              "- Corner A is assigned by a hash of the bout id, so A carries no information.", ""]
    n_test, n_com = len(test), len(common)
    lines += ["## Coverage", "",
              f"- Scored test bouts: {n_test}. With matched odds (the common set below): {n_com} ({n_com / n_test:.0%}).", ""]

    lines += ["## Overall, common set", "", "| Model | Log loss | Brier | Accuracy | AUC | ECE |", "|---|---|---|---|---|---|"]
    names = {"multiplicative": "B0 multiplicative", "power": "B0 power", "shin": "B0 Shin", "elo": "B1 Elo", "coin": "Coin flip"}
    for k in ["coin", "elo", "multiplicative", "power", "shin"]:
        lines.append(f"| {names[k]} | {M.log_loss(p[k], y):.4f} | {M.brier(p[k], y):.4f} | {M.accuracy(p[k], y):.3f} | "
                     f"{M.auc(p[k], y):.3f} | {M.ece(p[k], y):.3f} |")
    lines += ["", f"Default benchmark (lowest ECE of the three, per spec): **{names[default]}**.", ""]

    lines += ["## Log-loss gap, paired bootstrap (5000 resamples, 95% interval)", "",
              "Positive means the first model is worse.", "",
              "| Comparison | Mean difference [95% CI] |", "|---|---|"]
    for a, bname in [("elo", default), ("coin", default), ("elo", "coin")]:
        lines.append(f"| {names[a]} minus {names[bname]} | {_fmt_ci(M.paired_bootstrap_diff(ll[a], ll[bname]))} |")
    lines += [""]

    lines += ["## Reliability (deciles, common set)", "", "| Decile | Market mean p | Market observed | Elo mean p | Elo observed |", "|---|---|---|---|---|"]
    rm, re_ = M.reliability(p[default], y), M.reliability(p["elo"], y)
    for i, (a, c) in enumerate(zip(rm, re_), 1):
        lines.append(f"| {i} | {a['mean_p']:.3f} | {a['observed']:.3f} | {c['mean_p']:.3f} | {c['observed']:.3f} |")
    lines += [""]

    def segment_table(title, keyfn, min_n=MIN_SEGMENT):
        groups = defaultdict(list)
        for i, b in enumerate(common):
            groups[keyfn(b)].append(i)
        rows = [f"## {title}", "", "| Segment | n | Market LL | Elo LL | Elo minus market [95% CI] |", "|---|---|---|---|---|"]
        for g, idx in sorted(groups.items(), key=lambda kv: str(kv[0])):
            if len(idx) < min_n:
                continue
            idx = np.array(idx)
            rows.append(f"| {g} | {len(idx)} | {ll[default][idx].mean():.4f} | {ll['elo'][idx].mean():.4f} | "
                        f"{_fmt_ci(M.paired_bootstrap_diff(ll['elo'][idx], ll[default][idx]))} |")
        return rows + [""]

    lines += segment_table("By year", lambda b: b.date[:4])
    lines += segment_table("By sex", lambda b: "Women" if meta[b.bout_id]["weight_class"].startswith("Women") else "Men")
    lines += segment_table("By debutant (either fighter has no earlier UFC bout in this data)",
                           lambda b: "Debutant" if debut[b.bout_id] else "Experienced")
    lines += segment_table("By division (n >= 100)", lambda b: meta[b.bout_id]["weight_class"])
    lines += ["Segments not available from this dataset: main card vs prelims, five vs three rounds, tagged vs untagged.", ""]

    # elo on the full test window (not only bouts with odds)
    ye = np.array([b.score_a for b in test])
    pe = np.array([elo[b.bout_id] for b in test])
    lines += ["## Elo on the full test window", "",
              f"n = {len(test)}; log loss {M.log_loss(pe, ye):.4f}, Brier {M.brier(pe, ye):.4f}, accuracy {M.accuracy(pe, ye):.3f}, "
              f"AUC {M.auc(pe, ye):.3f}, ECE {M.ece(pe, ye):.3f}.", ""]

    if report_path:
        with open(report_path, "w", encoding="utf-8") as f:
            f.write("\n".join(lines))
    # predictions table: one row per bout and model
    pred_rows = []
    for b in test:
        pred_rows.append((b.bout_id, "B1_elo", elo[b.bout_id], b.date))
        if b.bout_id in mkt:
            for m in METHODS:
                pred_rows.append((b.bout_id, f"B0_{m}", mkt[b.bout_id][m], b.date))
    con.execute("CREATE OR REPLACE TABLE predictions (bout_id VARCHAR, model VARCHAR, p_red DOUBLE, snapshot_date DATE)")
    con.executemany("INSERT INTO predictions VALUES (?, ?, ?, ?)", pred_rows)
    return "\n".join(lines)
